import { cp, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const repositoryRoot = process.cwd();
const upstreamRoot = path.resolve(process.argv[2] ?? "");
const upstreamComponents = path.join(
  upstreamRoot,
  "registry-reui/bases/radix/components",
);
const upstreamMetadata = path.join(
  upstreamRoot,
  "registry-reui/_meta/components/registry.json",
);
const catalogueRoot = path.join(
  repositoryRoot,
  "components/design-system/reui/catalogue",
);
const generatedRoot = path.join(
  repositoryRoot,
  "components/design-system/reui/catalogue-data",
);

if (!process.argv[2]) {
  throw new Error(
    "Pass the path to an official ReUI checkout, for example: node scripts/sync-reui-free-components.mjs /path/to/reui",
  );
}

const registry = JSON.parse(await readFile(upstreamMetadata, "utf8"));
const examples = [];

const replacements = [
  [/@\/registry-reui\/bases\/radix\/reui\//g, "@reui/components/"],
  [/@\/registry-reui\/bases\/radix\/hooks\//g, "@reui/hooks/"],
  [/@\/registry\/bases\/radix\/ui\//g, "@reui/ui/"],
  [/@\/registry\/bases\/radix\/lib\/utils/g, "@reui/lib/utils"],
  [
    /@\/app\/\(create\)\/components\/icon-placeholder/g,
    "@reui/icon-placeholder",
  ],
  [/@\/components\/ui\/svgs\//g, "@reui/ui/svgs/"],
  [/@\/components\/ui\//g, "@reui/ui/"],
  [/@\/hooks\/use-copy-to-clipboard/g, "@reui/hooks/use-copy-to-clipboard"],
  [/@\/lib\/utils/g, "@reui/lib/utils"],
];

for (const category of registry.categories) {
  const sourceDirectory = path.join(upstreamComponents, category.name);
  const destinationDirectory = path.join(catalogueRoot, category.name);
  const metadata = JSON.parse(
    await readFile(path.join(sourceDirectory, "meta.json"), "utf8"),
  );

  await mkdir(destinationDirectory, { recursive: true });

  for (const example of metadata) {
    const sourcePath = path.join(sourceDirectory, `${example.name}.tsx`);
    const destinationPath = path.join(
      destinationDirectory,
      `${example.name}.tsx`,
    );
    let source = await readFile(sourcePath, "utf8");

    for (const [pattern, replacement] of replacements) {
      source = source.replace(pattern, replacement);
    }

    // Compatibility with the newer Recharts and generic calendar API versions
    // pinned by Coursemap. These preserve the rendered upstream examples.
    source = source.replace(
      /<ChartLegend\s+content=\{<ChartLegendContent nameKey="([^"]+)" \/>\}\s+className="([^"]+)"\s+\/>/g,
      '<ChartLegend content={<ChartLegendContent nameKey="$1" className="$2" />} />',
    );
    if (example.name === "c-event-calendar-4") {
      source = source.replace(
        "useRef<EventCalendarApi | null>",
        "useRef<EventCalendarApi<EventData> | null>",
      );
    }
    if (example.name === "c-event-calendar-5") {
      source = source.replace(
        "useRef<EventCalendarApi | null>",
        "useRef<EventCalendarApi<ApptData> | null>",
      );
    }

    await writeFile(destinationPath, source);
    examples.push({ category: category.name, ...example });
  }

  if (metadata.length !== category.count) {
    throw new Error(
      `${category.name} declares ${category.count} examples but contains ${metadata.length}`,
    );
  }
}

if (examples.length !== registry.totalComponents) {
  throw new Error(
    `Expected ${registry.totalComponents} examples but copied ${examples.length}`,
  );
}

const svgSource = path.join(upstreamRoot, "components/ui/svgs");
const svgDestination = path.join(
  repositoryRoot,
  "components/design-system/reui/ui/svgs",
);
await mkdir(svgDestination, { recursive: true });

for (const file of await readdir(svgSource)) {
  if (!file.endsWith(".tsx")) continue;
  await cp(path.join(svgSource, file), path.join(svgDestination, file));
}

await mkdir(generatedRoot, { recursive: true });

const catalogueSource = `// Generated by scripts/sync-reui-free-components.mjs.\n// Source: keenthemes/reui registry-reui Radix catalogue.\n\nexport type ReuiCatalogueExample = {\n  readonly category: string;\n  readonly name: string;\n  readonly title: string;\n  readonly description: string;\n  readonly order: number;\n  readonly gridSize?: number;\n  readonly previewHeight?: string;\n};\n\nexport type ReuiCatalogueCategory = {\n  readonly name: string;\n  readonly label: string;\n  readonly description: string;\n  readonly count: number;\n  readonly examples: readonly ReuiCatalogueExample[];\n};\n\nconst examples: readonly ReuiCatalogueExample[] = ${JSON.stringify(examples, null, 2)};\n\nexport const reuiCatalogueCategories = ${JSON.stringify(registry.categories, null, 2)}.map((category) => ({\n  ...category,\n  examples: examples.filter((example) => example.category === category.name),\n})) satisfies readonly ReuiCatalogueCategory[];\n\nexport const reuiCatalogueTotal = ${registry.totalComponents};\n\nexport function findReuiCategory(name: string) {\n  return reuiCatalogueCategories.find((category) => category.name === name);\n}\n\nexport function findReuiExample(categoryName: string, exampleName: string) {\n  return findReuiCategory(categoryName)?.examples.find((example) => example.name === exampleName);\n}\n`;

await writeFile(
  path.join(generatedRoot, "catalogue.generated.ts"),
  catalogueSource,
);

const navigationSource = `// Generated by scripts/sync-reui-free-components.mjs.\n// Source: keenthemes/reui registry-reui Radix catalogue.\n\nexport type ReuiCatalogueNavigationCategory = {\n  readonly name: string;\n  readonly label: string;\n  readonly count: number;\n};\n\nexport const reuiCatalogueNavigationCategories = ${JSON.stringify(
  registry.categories.map(({ name, label, count }) => ({ name, label, count })),
  null,
  2,
)} satisfies readonly ReuiCatalogueNavigationCategory[];\n`;

await writeFile(
  path.join(generatedRoot, "catalogue-navigation.generated.ts"),
  navigationSource,
);

const loaderEntries = examples
  .map(
    (example) =>
      `  ${JSON.stringify(example.name)}: dynamic(() => import("@reui/catalogue/${example.category}/${example.name}"), { ssr: false }),`,
  )
  .join("\n");

const loadersSource = `"use client";\n\n// Generated by scripts/sync-reui-free-components.mjs.\nimport type { ComponentType } from "react";\nimport dynamic from "next/dynamic";\n\nexport const reuiExampleComponents: Record<string, ComponentType> = {\n${loaderEntries}\n};\n`;

await writeFile(
  path.join(generatedRoot, "example-components.generated.tsx"),
  loadersSource,
);

console.log(
  `Copied ${examples.length} free ReUI Radix examples across ${registry.categories.length} categories.`,
);
